function summary = summarizeFinalMonteCarloResults(allDesigns, passingDesigns, failureCounts, analysisOptions, optimisationOptions, rngState)
% summarizeFinalMonteCarloResults Build compact final Monte Carlo summary table.

nDesigns = height(allDesigns);
nPassing = height(passingDesigns);
if nDesigns > 0
    passRate = nPassing / nDesigns;
else
    passRate = NaN;
end

if nPassing > 0
    best = passingDesigns(1, :);
    bestWeight = best.weight_including_ribs_excluding_misc_lb(1);
    bestYield = best.max_yield_ratio(1);
    bestColumn = best.max_column_buckling_ratio(1);
    bestDivergence = best.divergence_ratio(1);
    bestCombined = best.max_active_combined_panel_ratio(1);
    bestIndex = best.index(1);
else
    bestWeight = NaN;
    bestYield = NaN;
    bestColumn = NaN;
    bestDivergence = NaN;
    bestCombined = NaN;
    bestIndex = NaN;
end

summary = table( ...
    nDesigns, ...
    nPassing, ...
    passRate, ...
    failureCounts.n_errors(1), ...
    failureCounts.n_yield_fail(1), ...
    failureCounts.n_column_buckling_fail(1), ...
    failureCounts.n_divergence_fail(1), ...
    failureCounts.n_panel_buckling_fail(1), ...
    bestIndex, ...
    bestWeight, ...
    bestYield, ...
    bestColumn, ...
    bestDivergence, ...
    bestCombined, ...
    analysisOptions.loadFactor, ...
    string(analysisOptions.loadFactorPurpose), ...
    logical(analysisOptions.usePanelIdealisation), ...
    displayMethodName(analysisOptions.panelIdealisationMethod), ...
    logical(analysisOptions.enablePanelBuckling), ...
    logical(analysisOptions.panelBuckling.enableCombinedRatios), ...
    logical(analysisOptions.panelBuckling.useBayAveragedRecovery), ...
    logical(analysisOptions.panelBuckling.enableCurvedPanelCorrection), ...
    optimisationOptions.numDesigns, ...
    string(optimisationOptions.seedMode), ...
    string(rngState.Type), ...
    rngState.Seed, ...
    string(rngState.stateString), ...
    optimisationOptions.optionCounts.n_valid_stringers, ...
    optimisationOptions.optionCounts.n_valid_spar_caps, ...
    string(optimisationOptions.optionFilters.stringers), ...
    string(optimisationOptions.optionFilters.sparCaps), ...
    'VariableNames', { ...
    'n_designs', ...
    'n_passing', ...
    'pass_rate', ...
    'n_errors', ...
    'n_yield_fail', ...
    'n_column_buckling_fail', ...
    'n_divergence_fail', ...
    'n_panel_buckling_fail', ...
    'best_index', ...
    'best_weight_including_ribs_excluding_misc_lb', ...
    'best_yield_ratio', ...
    'best_column_buckling_ratio', ...
    'best_divergence_ratio', ...
    'best_active_combined_panel_ratio', ...
    'loadFactor', ...
    'loadFactorPurpose', ...
    'usePanelIdealisation', ...
    'panelIdealisationMethod', ...
    'enablePanelBuckling', ...
    'enableCombinedPanelRatios', ...
    'useBayAveragedRecovery', ...
    'enableCurvedPanelCorrection', ...
    'requested_numDesigns', ...
    'seedMode', ...
    'rngType', ...
    'rngSeed', ...
    'rngState', ...
    'n_valid_stringer_options', ...
    'n_valid_spar_cap_options', ...
    'stringer_filter', ...
    'spar_cap_filter'});
end

function label = displayMethodName(methodName)
methodName = string(methodName);
switch methodName
    case "modified_megson_z_ratio"
        label = "modified_megson_panel_idealisation";
    otherwise
        label = methodName;
end
end
