function plotSupplementaryReportFigures(outputRoot)
% plotSupplementaryReportFigures Rebuild the report figures and summary
% tables that are not produced by the optimisation/export functions.
%
%   plotSupplementaryReportFigures() writes into outputs/figures and
%   outputs/tables of the project. plotSupplementaryReportFigures(folder)
%   writes into folder/figures and folder/tables instead (used to compare
%   against the delivered files without overwriting them).
%
% Figures produced (all from saved data or from re-analysing the stored
% final candidate, no new optimisation):
%   final_flight_envelope.png                     copy of the V-n diagram made by initialLoadGeneration
%   final_all_cases_vertical_loads.png            q_z, V_z, M_x of the nine cases at ultimate load
%   final_all_cases_drag_torsion_loads.png        q_x, V_x, M_z, M_y of the nine cases at ultimate load
%   final_adaptive_failure_breakdown_by_stage.png failure counts per Monte Carlo stage
%   final_adaptive_passing_weight_histogram_by_stage.png  passing-design weights per stage
%   final_spanwise_bending_stress.png             max |bending stress| at each rib station
%   final_spanwise_panel_shear_stress.png         max |panel shear stress| at each rib station
%   final_spanwise_shear_flow.png                 max |shear flow| at each rib station
% Tables produced:
%   final_adaptive_failure_breakdown_by_stage.csv, final_stress_spanwise_summary.csv,
%   final_loads_spanwise_summary.csv, final_load_case_summary.csv

codeFolder = fileparts(mfilename('fullpath'));
projectRoot = fullfile(codeFolder, '..');
if nargin < 1 || isempty(outputRoot)
    figuresFolder = fullfile(projectRoot, 'outputs', 'figures');
    tablesFolder = fullfile(projectRoot, 'outputs', 'tables');
else
    figuresFolder = fullfile(outputRoot, 'figures');
    tablesFolder = fullfile(outputRoot, 'tables');
end
if ~exist(figuresFolder, 'dir'), mkdir(figuresFolder); end
if ~exist(tablesFolder, 'dir'), mkdir(tablesFolder); end
inputTables = fullfile(projectRoot, 'outputs', 'tables');

analysisOptions = defaultFinalAnalysisOptions();
loadFactor = analysisOptions.loadFactor;
caseTable = readtable(fullfile(projectRoot, 'data', 'critical_load_cases.csv'), 'TextType', 'string');
saved = load(fullfile(projectRoot, 'data', 'spanwise_loads.mat'));
spanwise = saved.spanwiseLoads;

% 1. V-n diagram (generated by initialLoadGeneration).
vn = fullfile(projectRoot, 'outputs', 'figures', 'load_cases', 'vn_diagram.png');
copyfile(vn, fullfile(figuresFolder, 'final_flight_envelope.png'), 'f');

% 2-3. Ultimate spanwise loads of all cases.
plotAllCaseLoads(spanwise, loadFactor, figuresFolder);
writeLoadTables(caseTable, spanwise, loadFactor, tablesFolder);

% 4-5. Monte Carlo stage figures.
stageSummary = readtable(fullfile(inputTables, 'final_adaptive_monte_carlo_stage_summary.csv'));
results = readtable(fullfile(inputTables, 'final_adaptive_monte_carlo_results.csv'), 'TextType', 'string');
plotFailureBreakdown(stageSummary, figuresFolder, tablesFolder);
plotPassingHistograms(results, figuresFolder);

% 6-8. Station maxima of the stored final candidate.
candidate = readtable(fullfile(inputTables, 'final_candidate_summary.csv'), 'TextType', 'string');
stations = stationMaxima(candidate, caseTable, spanwise, analysisOptions);
writetable(stations, fullfile(tablesFolder, 'final_stress_spanwise_summary.csv'));
plotStationCurve(stations.y_ft, stations.max_abs_bending_stress_psi / 1000, ...
    'Max absolute bending stress (ksi)', 'Maximum Bending Stress by Spanwise Station', ...
    fullfile(figuresFolder, 'final_spanwise_bending_stress.png'));
plotStationCurve(stations.y_ft, stations.max_abs_panel_shear_stress_psi / 1000, ...
    'Max absolute panel shear stress (ksi)', 'Maximum Panel Shear Stress by Spanwise Station', ...
    fullfile(figuresFolder, 'final_spanwise_panel_shear_stress.png'));
plotStationCurve(stations.y_ft, stations.max_abs_shear_flow_lb_per_in, ...
    'Max absolute shear flow (lb/in)', 'Maximum Shear Flow by Spanwise Station', ...
    fullfile(figuresFolder, 'final_spanwise_shear_flow.png'));
end

%% ------------------------------------------------------------ loads
function styles = caseStyles()
styles = {'-', '--o', ':s', '-.^', '-d', '--v', ':>', '-.<', '-p'};
end

function plotSeries(y, values, names)
styles = caseStyles();
hold on;
markerIdx = round(linspace(1, numel(y), 5));
for k = 1:size(values, 2)
    plot(y, values(:, k), styles{mod(k - 1, numel(styles)) + 1}, 'LineWidth', 1.3, ...
        'MarkerIndices', markerIdx, 'MarkerSize', 4, 'DisplayName', names(k));
end
grid on;
xlim([min(y), max(y)]);
end

function [y, Z, X] = caseMatrices(spanwise, loadFactor)
y = spanwise.y(:);
n = numel(spanwise.distZ);
Z.q = zeros(numel(y), n); Z.V = Z.q; Z.M = Z.q;
X.q = Z.q; X.V = Z.q; X.M = Z.q; X.My = Z.q;
for k = 1:n
    Z.q(:, k) = loadFactor * spanwise.distZ{k}.q(:);
    Z.V(:, k) = loadFactor * spanwise.distZ{k}.V(:);
    Z.M(:, k) = loadFactor * spanwise.distZ{k}.M(:);
    X.q(:, k) = loadFactor * spanwise.distX{k}.qx(:);
    X.V(:, k) = loadFactor * spanwise.distX{k}.Vx(:);
    X.M(:, k) = loadFactor * spanwise.distX{k}.Mz(:);
    X.My(:, k) = loadFactor * spanwise.distMy{k}.My_dist(:);
end
end

function plotAllCaseLoads(spanwise, loadFactor, figuresFolder)
names = string(spanwise.caseNames(:));
[y, Z, X] = caseMatrices(spanwise, loadFactor);

fig = figure('Visible', 'off', 'Color', 'w', 'Position', [60 60 1500 620]);
tiledlayout(1, 3, 'TileSpacing', 'compact', 'Padding', 'compact');
panels = {Z.q, 'Distributed normal load, q_z(y)', 'q_z (lb/ft)'
    Z.V, 'Vertical shear, V_z(y)', 'V_z (lb)'
    Z.M, 'Bending moment, M_x(y)', 'M_x (lb-ft)'};
for p = 1:3
    nexttile;
    plotSeries(y, panels{p, 1}, names);
    title(panels{p, 2});
    ylabel(panels{p, 3});
    xlabel('Span station, y (ft)');
end
legend('Location', 'eastoutside', 'Interpreter', 'none', 'FontSize', 8);
sgtitle(sprintf('Final Applied Vertical Load Components for All Critical Cases, Load Factor = %.1f', loadFactor));
exportgraphics(fig, fullfile(figuresFolder, 'final_all_cases_vertical_loads.png'), 'Resolution', 220);
close(fig);

fig = figure('Visible', 'off', 'Color', 'w', 'Position', [60 60 1600 780]);
tiledlayout(2, 2, 'TileSpacing', 'compact', 'Padding', 'compact');
panels = {X.q, 'Chordwise distributed load, q_x(y)', 'q_x (lb/ft)'
    X.V, 'Chordwise shear, V_x(y)', 'V_x (lb)'
    X.M, 'In-plane bending moment, M_z(y)', 'M_z (lb-ft)'
    X.My, 'Aerodynamic torsion, M_y(y)', 'M_y (lb-ft)'};
for p = 1:4
    nexttile;
    plotSeries(y, panels{p, 1}, names);
    title(panels{p, 2});
    ylabel(panels{p, 3});
    xlabel('Span station, y (ft)');
end
legend('Location', 'eastoutside', 'Interpreter', 'none', 'FontSize', 8);
sgtitle(sprintf('Final Applied Drag and Torsion Components for All Critical Cases, Load Factor = %.1f', loadFactor));
exportgraphics(fig, fullfile(figuresFolder, 'final_all_cases_drag_torsion_loads.png'), 'Resolution', 220);
close(fig);
end

function writeLoadTables(caseTable, spanwise, loadFactor, tablesFolder)
names = string(spanwise.caseNames(:));
[~, Z, X] = caseMatrices(spanwise, loadFactor);
n = numel(names);
rootV = @(d, f) cellfun(@(s) s.(f), d(:));

spanRows = table(names, loadFactor * rootV(spanwise.distX, 'Vx_root'), ...
    loadFactor * rootV(spanwise.distZ, 'V_root'), loadFactor * rootV(spanwise.distZ, 'M_root'), ...
    loadFactor * rootV(spanwise.distX, 'Mz_root'), loadFactor * rootV(spanwise.distMy, 'My_root'), ...
    max(abs(X.V))', max(abs(Z.V))', max(abs(Z.M))', max(abs(X.M))', max(abs(X.My))', ...
    repmat(loadFactor, n, 1), 'VariableNames', {'case_name', 'root_Vx_lb', 'root_Vz_lb', ...
    'root_Mx_lbft', 'root_Mz_lbft', 'root_My_lbft', 'max_abs_Vx_lb', 'max_abs_Vz_lb', ...
    'max_abs_Mx_lbft', 'max_abs_Mz_lbft', 'max_abs_My_lbft', 'loadFactor'});
writetable(spanRows, fullfile(tablesFolder, 'final_loads_spanwise_summary.csv'));

c = caseTable;
limitVx = c.Vx_root_lb; limitVz = c.Vz_root_lb;
limitMx = 12 * c.Mx_root_lbft; limitMz = 12 * c.Mz_root_lbft;
limitMy = 12 * c.My_root_lbft_or_semispan_value;
caseRows = table(c.case_name, c.V_mph, c.n, c.W_lb, c.alpha_deg, c.CL, c.CD, c.CM, c.CN, c.CX, ...
    limitVx, limitVz, limitMx, limitMz, limitMy, loadFactor * limitVx, loadFactor * limitVz, ...
    loadFactor * limitMx, loadFactor * limitMz, loadFactor * limitMy, repmat(loadFactor, height(c), 1), ...
    'VariableNames', {'case_name', 'V_mph', 'n', 'W_lb', 'alpha_deg', 'CL', 'CD', 'CM', 'CN', 'CX', ...
    'root_Vx_lb_limit', 'root_Vz_lb_limit', 'root_Mx_lbin_limit', 'root_Mz_lbin_limit', ...
    'root_My_lbin_limit', 'root_Vx_lb_final', 'root_Vz_lb_final', 'root_Mx_lbin_final', ...
    'root_Mz_lbin_final', 'root_My_lbin_final', 'loadFactor'});
writetable(caseRows, fullfile(tablesFolder, 'final_load_case_summary.csv'));
end

%% ------------------------------------------------------- Monte Carlo
function plotFailureBreakdown(stageSummary, figuresFolder, tablesFolder)
counts = [stageSummary.n_yield_fail, stageSummary.n_column_buckling_fail, ...
    stageSummary.n_divergence_fail, stageSummary.n_panel_buckling_fail, stageSummary.n_errors];
breakdown = table(stageSummary.stage, counts(:, 1), counts(:, 2), counts(:, 3), counts(:, 4), counts(:, 5), ...
    'VariableNames', {'stage', 'yield_failures', 'column_failures', 'divergence_failures', ...
    'panel_buckling_failures', 'errors'});
writetable(breakdown, fullfile(tablesFolder, 'final_adaptive_failure_breakdown_by_stage.csv'));

fig = figure('Visible', 'off', 'Color', 'w', 'Position', [100 100 950 560]);
bar(stageSummary.stage, counts);
grid on;
xlabel('Stage');
ylabel('Number of designs');
title('Adaptive Monte Carlo Failure Counts by Stage');
legend({'Yield', 'Column', 'Divergence', 'Panel buckling', 'Errors'}, ...
    'Location', 'northoutside', 'Orientation', 'horizontal');
exportgraphics(fig, fullfile(figuresFolder, 'final_adaptive_failure_breakdown_by_stage.png'), 'Resolution', 200);
close(fig);
end

function plotPassingHistograms(results, figuresFolder)
stages = unique(results.stage)';
passing = results.overall_pass == 1 & results.error_flag == 0;
fig = figure('Visible', 'off', 'Color', 'w', 'Position', [100 100 983 675]);
tiledlayout(numel(stages), 1, 'TileSpacing', 'compact', 'Padding', 'compact');
for s = stages
    nexttile;
    histogram(results.weight_including_ribs_excluding_misc_lb(passing & results.stage == s), 'NumBins', 25);
    grid on;
    xlabel('Weight including ribs, excluding misc (lb)');
    ylabel('Count');
    title(sprintf('Stage %d: Passing Design Weights', s));
end
exportgraphics(fig, fullfile(figuresFolder, 'final_adaptive_passing_weight_histogram_by_stage.png'), 'Resolution', 200);
close(fig);
end

%% --------------------------------------------- station maxima (final design)
function T = stationMaxima(candidate, caseTable, spanwise, analysisOptions)
design = designFromCandidate(candidate);
loads = criticalLoads(caseTable, spanwise);
result = analyzeWingDesignSpanwise(design, loads, loadDesignOptions(), analysisOptions);
st = result.stationResults;
n = numel(st);
T = table('Size', [n 9], 'VariableTypes', repmat({'double'}, 1, 9), 'VariableNames', ...
    {'station_index', 'y_in', 'y_ft', 'max_abs_bending_stress_psi', 'max_abs_shear_flow_lb_per_in', ...
    'max_abs_panel_shear_stress_psi', 'max_von_mises_psi', 'max_yield_ratio', 'max_column_ratio'});
for k = 1:n
    T.station_index(k) = st(k).station_index;
    T.y_in(k) = st(k).y_in;
    T.y_ft(k) = st(k).y_ft;
    T.max_abs_bending_stress_psi(k) = max(abs(st(k).stresses.bending.sigma_psi), [], 'all');
    T.max_abs_shear_flow_lb_per_in(k) = max(abs(st(k).shearFlows.shear.q_lb_per_in), [], 'all');
    T.max_abs_panel_shear_stress_psi(k) = max(abs(st(k).shearStress.panelShear.tau_psi), [], 'all');
    T.max_von_mises_psi(k) = max(st(k).vonMises.panel.sigma_vm_psi, [], 'all');
    T.max_yield_ratio(k) = max(st(k).yieldScreening.yield_ratio, [], 'all');
    T.max_column_ratio(k) = max(st(k).columnBuckling.buckling_ratio, [], 'all');
end
end

function d = designFromCandidate(c)
d = baselineDesign();
d.box.frontSpar_xc = c.frontSpar_xc(1);
d.box.rearSpar_xc = c.rearSpar_xc(1);
d.stringers.section_key = string(c.stringer_section_key(1));
d.stringers.sec_no = c.stringer_sec_no(1);
d.sparCaps.sec_no = c.spar_cap_sec_no(1);
d.thickness.t3_upperMainSkin_in = c.main_skin_t(1);
d.thickness.t4_lowerMainSkin_in = c.main_skin_t(1);
d.thickness.upperNoseSkin_in = c.noseSkin_t(1);
d.thickness.lowerNoseSkin_in = c.noseSkin_t(1);
d.thickness.t5_noseSkin_in = c.noseSkin_t(1);
d.thickness.t1_frontSpar_in = c.t1_frontSpar_in(1);
d.thickness.t2_rearSpar_in = c.t2_rearSpar_in(1);
d.stringers.numTop = c.numTop(1);
d.stringers.numBottom = c.numBottom(1);
d.stringers.numNoseTop = c.numNoseTop(1);
d.stringers.numNoseBottom = c.numNoseBottom(1);
d.ribs.ribSpacing_in = c.ribSpacing_in(1);
d.ribs.weightModel = "geometric_airfoil_area";
d.columnBuckling.K_column = c.K_column(1);
end

function plotStationCurve(y_ft, values, yLabel, titleText, fileName)
fig = figure('Visible', 'off', 'Color', 'w', 'Position', [100 100 900 500]);
plot(y_ft, values, '-o', 'LineWidth', 1.5);
grid on;
xlabel('Span y (ft)');
ylabel(yLabel);
title(titleText);
exportgraphics(fig, fileName, 'Resolution', 200);
close(fig);
end
